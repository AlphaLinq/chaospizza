#!/usr/bin/env python3
"""Generate a Luau snippet that loads src/ into an open Studio place (Edit mode).

Fallback for agents using the Roblox Studio MCP when `rojo serve` is not running:
    python3 tools/gen_studio_sync.py            > /tmp/sync.luau   # everything
    python3 tools/gen_studio_sync.py --changed  > /tmp/sync.luau   # only files changed
                                                                    # since the last --changed/--full run
then run the snippet with the MCP `execute_luau` tool (datamodel_type: Edit).

It mirrors default.project.json (Shared / Server / Client). Scripts are upserted
in place (Source replaced), so Rojo can take over later without conflicts.
Never edit the synced scripts in Studio; change src/ and re-sync.
State of the last sync is kept in .studio_sync_state.json (git-ignored).
"""
import hashlib
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ROOT = REPO / "src"
STATE = REPO / ".studio_sync_state.json"
MAPPING = {
    "shared": ("ReplicatedStorage", "Shared"),
    "server": ("ServerScriptService", "Server"),
    "client": ("StarterPlayer.StarterPlayerScripts", "Client"),
}
OPEN, CLOSE = "[===[", "]===]"

PRELUDE = r'''-- Generated by tools/gen_studio_sync.py. Run in Studio (Edit).
local function service(path)
	local inst = game
	for part in string.gmatch(path, "[^%.]+") do
		inst = inst:FindFirstChild(part) or game:GetService(part)
	end
	return inst
end
local function ensureRoot(servicePath, name, class)
	local parent = service(servicePath)
	local inst = parent:FindFirstChild(name)
	if inst and inst.ClassName ~= class then
		local replacement = Instance.new(class)
		replacement.Name = name
		for _, child in inst:GetChildren() do child.Parent = replacement end
		inst:Destroy()
		replacement.Parent = parent
		inst = replacement
	elseif not inst then
		inst = Instance.new(class)
		inst.Name = name
		inst.Parent = parent
	end
	return inst
end
local function ensureFolder(parent, name)
	local f = parent:FindFirstChild(name)
	if not f then
		f = Instance.new("Folder")
		f.Name = name
		f.Parent = parent
	end
	return f
end
local count = 0
local function upsert(root, folders, class, name, src)
	local parent = root
	for _, folderName in folders do parent = ensureFolder(parent, folderName) end
	local inst = parent:FindFirstChild(name)
	if inst and inst.ClassName ~= class then inst:Destroy() inst = nil end
	if not inst then
		inst = Instance.new(class)
		inst.Name = name
		inst.Parent = parent
	end
	inst.Source = src
	count += 1
end
local function remove(root, folders, name)
	local parent = root
	for _, folderName in folders do
		parent = parent and parent:FindFirstChild(folderName)
	end
	local inst = parent and parent:FindFirstChild(name)
	if inst then inst:Destroy() end
end
'''


def class_and_name(path: pathlib.Path):
    stem = path.stem
    if stem.endswith(".server"):
        return "Script", stem[: -len(".server")]
    if stem.endswith(".client"):
        return "LocalScript", stem[: -len(".client")]
    return "ModuleScript", stem


def lstr(text: str) -> str:
    if CLOSE in text:
        sys.exit("file contains ]===]; pick another long-string level")
    return f"{OPEN}{text}{CLOSE}"


def lua_list(items):
    return "{" + ", ".join(f'"{i}"' for i in items) + "}"


def collect():
    files = {}
    for path in sorted(ROOT.rglob("*.luau")):
        files[str(path.relative_to(ROOT))] = path
    return files


def main():
    changed_only = "--changed" in sys.argv
    files = collect()
    hashes = {rel: hashlib.sha1(p.read_bytes()).hexdigest() for rel, p in files.items()}
    old = json.loads(STATE.read_text()) if (changed_only and STATE.exists()) else {}

    out = [PRELUDE]
    for key, (service, name) in MAPPING.items():
        base = ROOT / key
        init = next((c for c in base.iterdir() if c.name.startswith("init.")), None)
        root_class = class_and_name(init)[0] if init else "Folder"
        out.append(f'do local root = ensureRoot("{service}", "{name}", "{root_class}")')
        for rel, path in files.items():
            if not rel.startswith(key + "/"):
                continue
            if changed_only and old.get(rel) == hashes[rel]:
                continue
            inner = pathlib.Path(rel).relative_to(key)
            if inner.name.startswith("init."):
                out.append(f"root.Source = {lstr(path.read_text(encoding='utf-8'))} count += 1")
                continue
            cls, mod = class_and_name(inner)
            folders = list(inner.parent.parts)
            out.append(f'upsert(root, {lua_list(folders)}, "{cls}", "{mod}", {lstr(path.read_text(encoding="utf-8"))})')
        for rel in old:
            if rel.startswith(key + "/") and rel not in files:
                inner = pathlib.Path(rel).relative_to(key)
                out.append(f'remove(root, {lua_list(list(inner.parent.parts))}, "{class_and_name(inner)[1]}")')
        out.append("end")
    out.append('return "synced " .. count .. " scripts"')
    print("\n".join(out))
    STATE.write_text(json.dumps(hashes, indent=1))


if __name__ == "__main__":
    main()

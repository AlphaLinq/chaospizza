#!/usr/bin/env python3
"""Generate a Luau snippet that loads src/ into an open Studio place (Edit mode).

Fallback for agents using the Roblox Studio MCP when `rojo serve` is not running:
    python3 tools/gen_studio_sync.py > /tmp/sync.luau
then run the file's content with the MCP `execute_luau` tool (datamodel_type: Edit).

It mirrors default.project.json (Shared / Server / Client) and replaces those three
roots. Rojo overwrites the same instances when it connects, so nothing is lost —
but never edit the synced scripts in Studio; change src/ and re-sync.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src"
MAPPING = {
    "shared": ("ReplicatedStorage", "Shared"),
    "server": ("ServerScriptService", "Server"),
    "client": ("StarterPlayer.StarterPlayerScripts", "Client"),
}
DELIM_OPEN, DELIM_CLOSE = "[===[", "]===]"


def class_and_name(path: pathlib.Path):
    stem = path.stem
    if stem.endswith(".server"):
        return "Script", stem[: -len(".server")]
    if stem.endswith(".client"):
        return "LocalScript", stem[: -len(".client")]
    return "ModuleScript", stem


def source(path: pathlib.Path) -> str:
    text = path.read_text(encoding="utf-8")
    if DELIM_CLOSE in text:
        sys.exit(f"{path} contains {DELIM_CLOSE}; pick another long-string level")
    return f"{DELIM_OPEN}{text}{DELIM_CLOSE}"


def main():
    out = [
        "-- Generated by tools/gen_studio_sync.py. Run in Studio (Edit).",
        'local function get(path) local inst = game for part in string.gmatch(path, "[^%.]+") do '
        "inst = inst:FindFirstChild(part) or game:GetService(part) end return inst end",
        "local function mk(class, name, parent, src) local i = Instance.new(class) i.Name = name "
        "if src then i.Source = src end i.Parent = parent return i end",
        "local count = 0",
    ]
    counter = [0]

    def var():
        counter[0] += 1
        return f"v{counter[0]}"

    def emit(directory: pathlib.Path, parent: str):
        for p in sorted(directory.iterdir()):
            if p.name.startswith("init."):
                continue
            if p.is_dir():
                if any(c.name.startswith("init.") for c in p.iterdir()):
                    sys.exit(f"{p}: nested init scripts are not supported by this generator")
                v = var()
                out.append(f'local {v} = mk("Folder", "{p.name}", {parent})')
                emit(p, v)
            elif p.suffix == ".luau":
                cls, name = class_and_name(p)
                out.append(f'mk("{cls}", "{name}", {parent}, {source(p)}) count += 1')

    for key, (service, name) in MAPPING.items():
        directory = ROOT / key
        root_var = var()
        out.append(f'do local old = get("{service}"):FindFirstChild("{name}") if old then old:Destroy() end end')
        init = [c for c in directory.iterdir() if c.name.startswith("init.")]
        if init:
            cls, _ = class_and_name(init[0])
            out.append(f'local {root_var} = Instance.new("{cls}") {root_var}.Name = "{name}" '
                       f"{root_var}.Source = {source(init[0])} count += 1")
        else:
            out.append(f'local {root_var} = Instance.new("Folder") {root_var}.Name = "{name}"')
        emit(directory, root_var)
        out.append(f'{root_var}.Parent = get("{service}")')

    out.append('return "synced " .. count .. " scripts"')
    print("\n".join(out))


if __name__ == "__main__":
    main()
